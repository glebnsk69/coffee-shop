CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    price BIGINT NOT NULL,
    discount INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    category_id INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT chk_products_price CHECK (price >= 0),
    CONSTRAINT chk_products_discount CHECK (discount BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP  NOT NULL,
    duration BIGINT,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_order_status
        CHECK (order_status IN ('OPEN', 'INPROGRESS', 'COMPLETED', 'CANCELLED')
        )
);

CREATE TABLE IF NOT EXISTS order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    item_name  VARCHAR(255) NOT NULL,
    cost  BIGINT NOT NULL,
    discount INTEGER NOT NULL DEFAULT 0,
    quantity INTEGER NOT NULL,

    CONSTRAINT chk_order_item_cost CHECK (cost>=0),
    CONSTRAINT chk_order_item_discount CHECK (discount BETWEEN 0 AND 100),
    CONSTRAINT chk_order_item_quantity CHECK (quantity >0),

    CONSTRAINT fk_order_item_orders FOREIGN KEY (order_id) REFERENCES orders(id),
    CONSTRAINT fk_order_item_products FOREIGN KEY (product_id) REFERENCES products(id)

);